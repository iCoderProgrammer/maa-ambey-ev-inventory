package attachments

import (
	"context"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"regexp"
)

// ObjectStore keeps file bytes privately under server-generated keys. It never
// hands out URLs: files are read back only through the API after the caller
// has been authorised (SEC-005).
type ObjectStore interface {
	// Driver names the backend; it is stored with each attachment.
	Driver() string
	// Put writes r under key. It fails if the key exists, and leaves nothing
	// behind when r returns an error (e.g. the size limit was hit).
	Put(ctx context.Context, key string, r io.Reader) (int64, error)
	// Open returns the object for reading.
	Open(ctx context.Context, key string) (io.ReadSeekCloser, error)
	// Delete removes an object written by a failed upload. It is not used for
	// stored attachments, which are never deleted through the application.
	Delete(ctx context.Context, key string) error
}

// ErrObjectNotFound means the key has no stored object.
var ErrObjectNotFound = errors.New("attachment object not found")

var objectKeyPattern = regexp.MustCompile(`^[0-9]{4}/[0-9]{2}/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$`)

// LocalStore is the local-disk driver: a private directory, owner-only
// permissions, outside any web root. An S3-compatible driver is pending the
// hosting decision (ADR-010).
type LocalStore struct {
	root string
}

// NewLocalStore creates the root directory (0700) if needed and checks that it
// is writable, so a misconfiguration fails at start-up rather than on upload.
func NewLocalStore(root string) (*LocalStore, error) {
	abs, err := filepath.Abs(root)
	if err != nil {
		return nil, fmt.Errorf("attachment storage dir: %w", err)
	}
	if err := os.MkdirAll(abs, 0o700); err != nil {
		return nil, fmt.Errorf("attachment storage dir: %w", err)
	}
	probe, err := os.CreateTemp(abs, ".probe-*")
	if err != nil {
		return nil, fmt.Errorf("attachment storage dir is not writable: %w", err)
	}
	_ = probe.Close()
	_ = os.Remove(probe.Name())
	return &LocalStore{root: abs}, nil
}

// Driver implements ObjectStore.
func (s *LocalStore) Driver() string { return "local" }

func (s *LocalStore) path(key string) (string, error) {
	// Keys are generated by the server; the pattern also rules out traversal.
	if !objectKeyPattern.MatchString(key) {
		return "", fmt.Errorf("invalid object key %q", key)
	}
	return filepath.Join(s.root, filepath.FromSlash(key)), nil
}

// Put implements ObjectStore. The file is written to a temporary name and
// renamed into place, so a partial upload is never visible under its key.
func (s *LocalStore) Put(ctx context.Context, key string, r io.Reader) (int64, error) {
	p, err := s.path(key)
	if err != nil {
		return 0, err
	}
	if _, err := os.Stat(p); err == nil {
		return 0, fmt.Errorf("object %s already exists", key)
	}
	dir := filepath.Dir(p)
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return 0, err
	}
	tmp, err := os.CreateTemp(dir, ".upload-*")
	if err != nil {
		return 0, err
	}
	cleanup := func() { _ = tmp.Close(); _ = os.Remove(tmp.Name()) }
	n, err := io.Copy(tmp, readerWithContext{ctx, r})
	if err != nil {
		cleanup()
		return n, err
	}
	if err := tmp.Sync(); err != nil {
		cleanup()
		return n, err
	}
	if err := tmp.Close(); err != nil {
		_ = os.Remove(tmp.Name())
		return n, err
	}
	if err := os.Link(tmp.Name(), p); err != nil { // fails if the key appeared meanwhile
		_ = os.Remove(tmp.Name())
		return n, err
	}
	_ = os.Remove(tmp.Name())
	return n, nil
}

// Open implements ObjectStore.
func (s *LocalStore) Open(_ context.Context, key string) (io.ReadSeekCloser, error) {
	p, err := s.path(key)
	if err != nil {
		return nil, err
	}
	f, err := os.Open(p)
	if errors.Is(err, os.ErrNotExist) {
		return nil, ErrObjectNotFound
	}
	return f, err
}

// Delete implements ObjectStore.
func (s *LocalStore) Delete(_ context.Context, key string) error {
	p, err := s.path(key)
	if err != nil {
		return err
	}
	if err := os.Remove(p); err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	return nil
}

// readerWithContext stops a copy once the request is cancelled.
type readerWithContext struct {
	ctx context.Context
	r   io.Reader
}

func (r readerWithContext) Read(p []byte) (int, error) {
	if err := r.ctx.Err(); err != nil {
		return 0, err
	}
	return r.r.Read(p)
}
