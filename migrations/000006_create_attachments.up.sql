-- Private attachments (B-09, FR-016, SEC-005). File bytes live in private
-- storage under a generated object key; this table holds the metadata the API
-- authorises against. Files are never served from a public URL.

-- Catalogue keys only: no role is granted them (permission matrix RB-5 pending).
INSERT INTO permissions (key, description, sensitive) VALUES
    ('attachments.upload', 'Upload private attachments (documents and photos)', true),
    ('attachments.view',   'View and download private attachments',            true);

CREATE TABLE attachments (
    id             uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    -- Generated by the server (yyyy/mm/<uuid>); never derived from the file name.
    object_key     text        NOT NULL,
    storage_driver text        NOT NULL,
    -- Detected from the file content, not taken from the client.
    content_type   text        NOT NULL,
    size_bytes     bigint      NOT NULL,
    sha256         bytea       NOT NULL,
    -- Display name only (sanitised); not used for storage.
    original_name  text        NOT NULL,
    uploaded_by    uuid        NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    -- Location the file belongs to (scope check, SEC-002); NULL = not location-bound.
    location_id    uuid        REFERENCES locations (id) ON DELETE RESTRICT,
    -- Business record the file is attached to (set by later modules, e.g. GRN/PDI).
    -- NULL = not linked yet: only the uploader can see it.
    owner_type     text,
    owner_id       text,
    created_at     timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT attachments_object_key_format CHECK (object_key ~ '^[0-9]{4}/[0-9]{2}/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'),
    CONSTRAINT attachments_storage_driver_valid CHECK (storage_driver IN ('local')),
    CONSTRAINT attachments_content_type_valid CHECK (content_type IN ('image/jpeg', 'image/png', 'image/webp', 'application/pdf')),
    CONSTRAINT attachments_size_positive CHECK (size_bytes > 0),
    CONSTRAINT attachments_sha256_length CHECK (octet_length(sha256) = 32),
    CONSTRAINT attachments_original_name_length CHECK (length(btrim(original_name)) > 0 AND length(original_name) <= 200),
    CONSTRAINT attachments_owner_pair CHECK ((owner_type IS NULL) = (owner_id IS NULL)),
    CONSTRAINT attachments_owner_type_format CHECK (owner_type IS NULL OR (owner_type ~ '^[a-z][a-z0-9_]*$' AND length(owner_type) <= 60)),
    CONSTRAINT attachments_owner_id_length CHECK (owner_id IS NULL OR length(owner_id) BETWEEN 1 AND 100)
);
CREATE UNIQUE INDEX attachments_object_key_key ON attachments (storage_driver, object_key);
CREATE INDEX attachments_uploader_idx ON attachments (uploaded_by, created_at DESC);
CREATE INDEX attachments_owner_idx ON attachments (owner_type, owner_id) WHERE owner_type IS NOT NULL;
CREATE INDEX attachments_location_idx ON attachments (location_id) WHERE location_id IS NOT NULL;

-- Metadata is immutable and never hard-deleted. The only allowed change is
-- linking an unlinked attachment to its business record, once.
CREATE FUNCTION attachments_guard_change() RETURNS trigger AS $$
BEGIN
    IF TG_OP IN ('DELETE', 'TRUNCATE') THEN
        RAISE EXCEPTION 'attachments cannot be deleted (% refused)', TG_OP USING ERRCODE = 'insufficient_privilege';
    END IF;
    IF OLD.owner_type IS NOT NULL
       OR NEW.id IS DISTINCT FROM OLD.id
       OR NEW.object_key IS DISTINCT FROM OLD.object_key
       OR NEW.storage_driver IS DISTINCT FROM OLD.storage_driver
       OR NEW.content_type IS DISTINCT FROM OLD.content_type
       OR NEW.size_bytes IS DISTINCT FROM OLD.size_bytes
       OR NEW.sha256 IS DISTINCT FROM OLD.sha256
       OR NEW.original_name IS DISTINCT FROM OLD.original_name
       OR NEW.uploaded_by IS DISTINCT FROM OLD.uploaded_by
       OR NEW.location_id IS DISTINCT FROM OLD.location_id
       OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
        RAISE EXCEPTION 'attachment metadata is immutable; only linking an unlinked attachment is allowed'
            USING ERRCODE = 'insufficient_privilege';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER attachments_guard
    BEFORE UPDATE OR DELETE ON attachments
    FOR EACH ROW EXECUTE FUNCTION attachments_guard_change();

CREATE TRIGGER attachments_no_truncate
    BEFORE TRUNCATE ON attachments
    FOR EACH STATEMENT EXECUTE FUNCTION attachments_guard_change();
